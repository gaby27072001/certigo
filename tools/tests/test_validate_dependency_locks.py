from __future__ import annotations

import importlib.util
import json
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path


MODULE_PATH = Path(__file__).resolve().parents[1] / "validate_dependency_locks.py"
REPO_ROOT = Path(__file__).resolve().parents[2]
SPEC = importlib.util.spec_from_file_location("validate_dependency_locks", MODULE_PATH)
assert SPEC and SPEC.loader
validator = importlib.util.module_from_spec(SPEC)
sys.modules[SPEC.name] = validator
SPEC.loader.exec_module(validator)


class DependencyLockValidatorTests(unittest.TestCase):
    def setUp(self) -> None:
        self.temp_dir = tempfile.TemporaryDirectory()
        self.root = Path(self.temp_dir.name)
        subprocess.run(["git", "init", "-q"], cwd=self.root, check=True)
        self.write(
            "package.json",
            json.dumps({"name": "fixture", "devDependencies": {"example": "1.0.0"}}),
        )
        self.write(
            "package-lock.json",
            json.dumps(
                {
                    "name": "fixture",
                    "lockfileVersion": 3,
                    "packages": {
                        "": {
                            "name": "fixture",
                            "devDependencies": {"example": "1.0.0"},
                        }
                    },
                }
            ),
        )
        self.write(
            "packages/app/pubspec.yaml",
            "name: app\nenvironment:\n  sdk: ^3.0.0\ndependencies:\n  args: ^2.0.0\n",
        )
        self.write(
            "packages/app/pubspec.lock",
            "# Generated by pub\npackages:\n  args:\n    version: 2.0.0\nsdks:\n  dart: ^3.0.0\n",
        )
        self.write(
            "packages/core/pubspec.yaml",
            "name: core\nenvironment:\n  sdk: ^3.0.0\ndependencies: {}\n",
        )
        self.write(
            "packages/core/pubspec.lock",
            "# Generated by pub\npackages:\n{}\nsdks:\n  dart: ^3.0.0\n",
        )
        self.write(
            "backend/App/App.csproj",
            '<Project Sdk="Microsoft.NET.Sdk"></Project>',
        )
        self.write(
            "backend/App/packages.lock.json",
            '{"version":1,"dependencies":{"net8.0":{}}}',
        )
        self.add(
            "package.json",
            "package-lock.json",
            "packages/app/pubspec.yaml",
            "packages/app/pubspec.lock",
            "packages/core/pubspec.yaml",
            "packages/core/pubspec.lock",
            "backend/App/App.csproj",
            "backend/App/packages.lock.json",
        )

    def tearDown(self) -> None:
        self.temp_dir.cleanup()

    def write(self, relative: str, content: str) -> None:
        path = self.root / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")

    def add(self, *paths: str) -> None:
        subprocess.run(["git", "add", "--", *paths], cwd=self.root, check=True)

    def test_accepts_complete_lock_coverage_and_writes_osv_sources(self) -> None:
        output = self.root / "expected.json"
        self.assertEqual((1, 2, 1), validator.validate_repository(self.root, output))
        self.assertEqual(
            {
                "sources": [
                    "package-lock.json",
                    "packages/app/pubspec.lock",
                    "packages/core/pubspec.lock",
                ],
                "pubManifests": [
                    "packages/app/pubspec.yaml",
                    "packages/core/pubspec.yaml",
                ]
            },
            json.loads(output.read_text(encoding="utf-8")),
        )

    def test_rejects_legacy_empty_version_allowlist(self) -> None:
        output = self.root / "expected.json"
        output.write_text(
            json.dumps({"allowedEmptyNugetPackages": ["ProjectReference"]}),
            encoding="utf-8",
        )
        with self.assertRaisesRegex(
            validator.DependencyLockError,
            "allowedEmptyNugetPackages is forbidden",
        ):
            validator.validate_repository(self.root, output)

    def test_rejects_missing_or_stale_npm_lock(self) -> None:
        subprocess.run(
            ["git", "rm", "--cached", "package-lock.json"],
            cwd=self.root,
            check=True,
            capture_output=True,
        )
        with self.assertRaisesRegex(validator.DependencyLockError, "npm locks.*missing"):
            validator.validate_repository(self.root)

        self.add("package-lock.json")
        lock_path = self.root / "package-lock.json"
        value = json.loads(lock_path.read_text(encoding="utf-8"))
        value["packages"][""]["devDependencies"]["example"] = "2.0.0"
        lock_path.write_text(json.dumps(value), encoding="utf-8")
        with self.assertRaisesRegex(validator.DependencyLockError, "differs from"):
            validator.validate_repository(self.root)

    def test_rejects_missing_pub_lock_and_symlink_manifest(self) -> None:
        subprocess.run(
            ["git", "rm", "--cached", "packages/app/pubspec.lock"],
            cwd=self.root,
            check=True,
            capture_output=True,
        )
        with self.assertRaisesRegex(validator.DependencyLockError, "pub locks.*missing"):
            validator.validate_repository(self.root)

    def test_rejects_tracked_symlink_manifest(self) -> None:
        manifest = self.root / "package.json"
        target = self.root / "real-package.json"
        target.write_text(manifest.read_text(encoding="utf-8"), encoding="utf-8")
        manifest.unlink()
        try:
            manifest.symlink_to(target.name)
        except OSError as exc:
            self.skipTest(f"symlinks are unavailable: {exc}")
        with self.assertRaisesRegex(
            validator.DependencyLockError,
            r"unsafe or symbolic tracked path",
        ):
            validator.validate_repository(self.root)

    def test_excludes_generated_and_example_directories(self) -> None:
        self.write("examples/demo/package.json", '{"name":"ignored"}')
        self.write("build/generated/pubspec.yaml", "name: ignored\n")
        self.add("examples/demo/package.json", "build/generated/pubspec.yaml")
        self.assertEqual((1, 2, 1), validator.validate_repository(self.root))

    def test_repository_contract_lists_all_current_pub_manifests(self) -> None:
        output = self.root / "repository-expected.json"
        validator.validate_repository(REPO_ROOT, output)
        self.assertEqual(
            [
                "apps/mobile/pubspec.yaml",
                "packages/core/pubspec.yaml",
                "packages/cortex/pubspec.yaml",
                "packages/data/pubspec.yaml",
                "packages/prism_ui/pubspec.yaml",
            ],
            json.loads(output.read_text(encoding="utf-8"))["pubManifests"],
        )


if __name__ == "__main__":
    unittest.main()
