from __future__ import annotations

import importlib.util
import json
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path
from unittest import mock


MODULE_PATH = Path(__file__).resolve().parents[1] / "verify_pub_locks.py"
SPEC = importlib.util.spec_from_file_location("verify_pub_locks", MODULE_PATH)
assert SPEC and SPEC.loader
verifier = importlib.util.module_from_spec(SPEC)
sys.modules[SPEC.name] = verifier
SPEC.loader.exec_module(verifier)


class PubLockVerifierTests(unittest.TestCase):
    def setUp(self) -> None:
        self.temp_dir = tempfile.TemporaryDirectory()
        self.cache_dir = tempfile.TemporaryDirectory()
        self.root = Path(self.temp_dir.name)
        self.cache = Path(self.cache_dir.name)
        subprocess.run(["git", "init", "-q"], cwd=self.root, check=True)
        self.write(
            "packages/a/pubspec.yaml",
            "name: a\nenvironment:\n  sdk: ^3.0.0\n",
        )
        self.write(
            "packages/a/pubspec.lock",
            "# Generated by pub\npackages:\n{}\nsdks:\n  dart: ^3.0.0\n",
        )
        self.write(
            "packages/b/pubspec.yaml",
            "name: b\nenvironment:\n  sdk: ^3.0.0\n",
        )
        self.write(
            "packages/b/pubspec.lock",
            "# Generated by pub\npackages:\n{}\nsdks:\n  dart: ^3.0.0\n",
        )
        subprocess.run(["git", "add", "."], cwd=self.root, check=True)
        self.contract = self.root / "expected.json"
        self.contract.write_text(
            json.dumps(
                {
                    "pubManifests": [
                        "packages/a/pubspec.yaml",
                        "packages/b/pubspec.yaml",
                    ]
                }
            ),
            encoding="utf-8",
        )

    def tearDown(self) -> None:
        self.temp_dir.cleanup()
        self.cache_dir.cleanup()

    def write(self, relative: str, content: str) -> None:
        path = self.root / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")

    def test_resolves_every_contract_manifest_and_checks_git_diff(self) -> None:
        with mock.patch.object(verifier.subprocess, "run") as run:
            run.return_value = subprocess.CompletedProcess([], 0)
            self.assertEqual(
                2,
                verifier.verify_pub_locks(
                    self.root,
                    self.contract,
                    Path(sys.executable),
                    self.cache,
                ),
            )

        self.assertEqual(3, run.call_count)
        for call in run.call_args_list[:2]:
            self.assertEqual(
                [str(Path(sys.executable).resolve()), "pub", "get", "--enforce-lockfile"],
                call.args[0],
            )
            self.assertEqual(str(self.cache.resolve()), call.kwargs["env"]["PUB_CACHE"])
        self.assertEqual("git", run.call_args_list[-1].args[0][0])
        self.assertIn("packages/a/pubspec.lock", run.call_args_list[-1].args[0])
        self.assertIn("packages/b/pubspec.lock", run.call_args_list[-1].args[0])

    def test_rejects_lockfile_changes(self) -> None:
        lock = self.root / "packages/a/pubspec.lock"

        def mutate_lock(*args: object, **kwargs: object) -> subprocess.CompletedProcess:
            del kwargs
            command = args[0]
            if isinstance(command, list) and command[0] != "git":
                lock.write_text("changed\n", encoding="utf-8")
            return subprocess.CompletedProcess(command, 0)

        with mock.patch.object(verifier.subprocess, "run", side_effect=mutate_lock):
            with self.assertRaisesRegex(
                verifier.PubLockVerificationError,
                "changed the committed lockfile",
            ):
                verifier.verify_pub_locks(
                    self.root,
                    self.contract,
                    Path(sys.executable),
                    self.cache,
                )

    def test_rejects_unsafe_or_unsorted_contract_paths(self) -> None:
        for manifests in (
            ["../pubspec.yaml"],
            ["packages/b/pubspec.yaml", "packages/a/pubspec.yaml"],
            ["packages/a/pubspec.yaml", "packages/a/pubspec.yaml"],
        ):
            with self.subTest(manifests=manifests):
                self.contract.write_text(
                    json.dumps({"pubManifests": manifests}),
                    encoding="utf-8",
                )
                with self.assertRaises(verifier.PubLockVerificationError):
                    verifier.verify_pub_locks(
                        self.root,
                        self.contract,
                        Path(sys.executable),
                        self.cache,
                    )


if __name__ == "__main__":
    unittest.main()
