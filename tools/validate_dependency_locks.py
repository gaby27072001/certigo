#!/usr/bin/env python3
"""Validate tracked npm, pub, and NuGet lock coverage without running package managers."""

from __future__ import annotations

import argparse
import importlib.util
import json
import subprocess
import sys
from pathlib import Path, PurePosixPath


MODULE_PATH = Path(__file__).resolve().with_name("validate_nuget_locks.py")
SPEC = importlib.util.spec_from_file_location("validate_nuget_locks", MODULE_PATH)
assert SPEC and SPEC.loader
validate_nuget_locks = importlib.util.module_from_spec(SPEC)
sys.modules[SPEC.name] = validate_nuget_locks
SPEC.loader.exec_module(validate_nuget_locks)

EXCLUDED_PARTS = {
    ".dart_tool",
    "bin",
    "build",
    "example",
    "examples",
    "node_modules",
    "obj",
}


class DependencyLockError(RuntimeError):
    """Raised when tracked dependency manifests and locks diverge."""


def _tracked_paths(root: Path) -> tuple[PurePosixPath, ...]:
    try:
        result = subprocess.run(
            [
                "git",
                "-c",
                "core.hooksPath=/dev/null",
                "ls-files",
                "-z",
            ],
            cwd=root,
            check=True,
            capture_output=True,
        )
    except OSError as exc:
        raise DependencyLockError(f"Cannot execute git: {exc}") from exc
    except subprocess.CalledProcessError as exc:
        detail = exc.stderr.decode("utf-8", errors="replace").strip()
        raise DependencyLockError(f"git ls-files failed: {detail}") from exc
    return tuple(
        PurePosixPath(value.decode("utf-8"))
        for value in result.stdout.split(b"\0")
        if value
    )


def _included(path: PurePosixPath) -> bool:
    return not any(part.casefold() in EXCLUDED_PARTS for part in path.parts[:-1])


def _safe_file(root: Path, relative: PurePosixPath) -> Path:
    path = root.joinpath(*relative.parts)
    if relative.is_absolute() or ".." in relative.parts or path.is_symlink():
        raise DependencyLockError(f"{relative}: unsafe or symbolic tracked path.")
    try:
        canonical_root = root.resolve(strict=True)
        candidate = path.resolve(strict=True)
    except OSError as exc:
        raise DependencyLockError(f"Cannot resolve tracked file {relative}: {exc}") from exc
    if not candidate.is_relative_to(canonical_root) or not candidate.is_file():
        raise DependencyLockError(f"{relative}: expected a regular repository file.")
    return candidate


def _load_json(path: Path, source: PurePosixPath) -> dict[str, object]:
    try:
        value = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise DependencyLockError(f"{source}: invalid JSON: {exc}") from exc
    if not isinstance(value, dict):
        raise DependencyLockError(f"{source}: expected a JSON object.")
    return value


def _validate_npm_pair(root: Path, manifest: PurePosixPath, lock: PurePosixPath) -> None:
    manifest_value = _load_json(_safe_file(root, manifest), manifest)
    lock_value = _load_json(_safe_file(root, lock), lock)
    if lock_value.get("lockfileVersion") != 3 or not isinstance(
        lock_value.get("packages"), dict
    ):
        raise DependencyLockError(f"{lock}: expected npm lockfileVersion 3 packages data.")
    root_package = lock_value["packages"].get("")
    if not isinstance(root_package, dict):
        raise DependencyLockError(f"{lock}: missing root package entry.")
    for field in (
        "dependencies",
        "devDependencies",
        "optionalDependencies",
        "peerDependencies",
    ):
        manifest_dependencies = manifest_value.get(field, {})
        locked_dependencies = root_package.get(field, {})
        if not isinstance(manifest_dependencies, dict) or not isinstance(
            locked_dependencies, dict
        ):
            raise DependencyLockError(f"{manifest}/{lock}: {field} must be objects.")
        if manifest_dependencies != locked_dependencies:
            raise DependencyLockError(
                f"{lock}: root {field} differs from {manifest}."
            )


def _validate_pub_pair(root: Path, manifest: PurePosixPath, lock: PurePosixPath) -> None:
    manifest_text = _safe_file(root, manifest).read_text(encoding="utf-8")
    lock_text = _safe_file(root, lock).read_text(encoding="utf-8")
    if "\nenvironment:" not in f"\n{manifest_text}":
        raise DependencyLockError(f"{manifest}: expected an environment section.")
    if (
        not lock_text.startswith("# Generated by pub\n")
        or "\npackages:" not in f"\n{lock_text}"
        or "\nsdks:" not in f"\n{lock_text}"
    ):
        raise DependencyLockError(f"{lock}: malformed pub lockfile structure.")


def _require_adjacent_pairs(
    manifests: set[PurePosixPath],
    locks: set[PurePosixPath],
    lock_name: str,
    ecosystem: str,
) -> dict[PurePosixPath, PurePosixPath]:
    expected = {manifest.parent / lock_name for manifest in manifests}
    if locks != expected:
        missing = sorted(str(path) for path in expected - locks)
        orphaned = sorted(str(path) for path in locks - expected)
        raise DependencyLockError(
            f"{ecosystem} locks must map one-to-one with manifests "
            f"(missing={missing}, orphaned={orphaned})."
        )
    return {manifest: manifest.parent / lock_name for manifest in manifests}


def validate_repository(
    root: Path,
    expected_sources_file: Path | None = None,
) -> tuple[int, int, int]:
    canonical_root = root.resolve(strict=True)
    tracked = tuple(path for path in _tracked_paths(canonical_root) if _included(path))
    npm_manifests = {path for path in tracked if path.name == "package.json"}
    npm_locks = {path for path in tracked if path.name == "package-lock.json"}
    pub_manifests = {path for path in tracked if path.name == "pubspec.yaml"}
    pub_locks = {path for path in tracked if path.name == "pubspec.lock"}
    if not npm_manifests or not pub_manifests:
        raise DependencyLockError("Expected tracked npm and pub manifests.")

    npm_pairs = _require_adjacent_pairs(
        npm_manifests, npm_locks, "package-lock.json", "npm"
    )
    pub_pairs = _require_adjacent_pairs(
        pub_manifests, pub_locks, "pubspec.lock", "pub"
    )
    for manifest, lock in npm_pairs.items():
        _validate_npm_pair(canonical_root, manifest, lock)
    for manifest, lock in pub_pairs.items():
        _validate_pub_pair(canonical_root, manifest, lock)

    nuget_projects, _, _ = validate_nuget_locks.validate_repository(canonical_root)
    nuget_locks = {
        path
        for path in tracked
        if path.parts
        and path.parts[0] == "backend"
        and path.name.casefold() == "packages.lock.json"
    }
    empty_locks: set[PurePosixPath] = set()
    for lock in nuget_locks:
        value = json.loads(_safe_file(canonical_root, lock).read_text(encoding="utf-8"))
        dependencies = value.get("dependencies", {})
        if isinstance(dependencies, dict) and all(
            isinstance(graph, dict) and not graph for graph in dependencies.values()
        ):
            empty_locks.add(lock)
    expected_sources = sorted(
        str(path) for path in npm_locks | pub_locks | (nuget_locks - empty_locks)
    )
    if expected_sources_file is not None:
        expected_sources_file.parent.mkdir(parents=True, exist_ok=True)
        expected_sources_file.write_text(
            json.dumps(
                {
                    "sources": expected_sources,
                    "pubManifests": sorted(str(path) for path in pub_manifests),
                },
                indent=2,
            )
            + "\n",
            encoding="utf-8",
            newline="\n",
        )
    return len(npm_pairs), len(pub_pairs), nuget_projects


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--root",
        type=Path,
        default=Path(__file__).resolve().parents[1],
        help="repository root to validate",
    )
    parser.add_argument(
        "--write-expected-sources",
        type=Path,
        help="write the complete relative lockfile list for OSV coverage enforcement",
    )
    args = parser.parse_args(argv)
    try:
        npm_count, pub_count, nuget_count = validate_repository(
            args.root, args.write_expected_sources
        )
    except (DependencyLockError, validate_nuget_locks.NuGetLockError, OSError) as exc:
        print(f"dependency-locks: {exc}", file=sys.stderr)
        return 1
    print(
        f"Dependency locks valid: {npm_count} npm, {pub_count} pub, "
        f"{nuget_count} NuGet project(s)."
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
